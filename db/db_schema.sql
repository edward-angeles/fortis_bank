CREATE TABLE customers (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	first_name VARCHAR2(25) NOT NULL,
	last_name VARCHAR2(25) NOT NULL,
	pin NUMBER(4) NOT NULL,
	email VARCHAR2(35) NOT NULL,
	phone CHAR(12) NOT NULL,
	CONSTRAINT chk_customer_pin CHECK (pin BETWEEN 1000 AND 9999)
);

CREATE TABLE job_statuses (
	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(20) NOT NULL,
	description VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE bank_managers (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	first_name VARCHAR2(25) NOT NULL,
	last_name VARCHAR2(25) NOT NULL,
	email VARCHAR2(35) NOT NULL,
	status_id NUMBER(3) NOT NULL,
	CONSTRAINT fk_bm_job_status FOREIGN KEY (status_id) REFERENCES job_statuses(id)
);

CREATE TABLE bank_managers_customers (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	bank_manager_id NUMBER(19),
	customer_id NUMBER(19) NOT NULL,
	CONSTRAINT fk_bmc_customers FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE,
	CONSTRAINT fk_bmc_bank_managers FOREIGN KEY (bank_manager_id) REFERENCES bank_managers(id) ON DELETE SET NULL
);

CREATE TABLE report_types (
	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(15) NOT NULL,
	description VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE reports (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	generated_at DATE DEFAULT SYSDATE NOT NULL,
	report_type_id NUMBER(3) NOT NULL,
	report_content CLOB NOT NULL,
	author_id NUMBER(19) NOT NULL,
	recipient_id NUMBER(19) NOT NULL,
	CONSTRAINT fk_reports_report_type FOREIGN KEY (report_type_id) REFERENCES report_types(id),
	CONSTRAINT fk_reports_author FOREIGN KEY (author_id) REFERENCES bank_managers(id),
	CONSTRAINT fk_reports_recipient FOREIGN KEY (recipient_id) REFERENCES customers(id)
);

CREATE TABLE account_statuses (
   	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(25) NOT NULL,
	description VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE account_types ( 
	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(25) NOT NULL, -- e.g., 'CHECKING', 'SAVINGS'
	description VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE accounts (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id NUMBER(19) NOT NULL,
	status_id NUMBER(3) NOT NULL,
	type_id NUMBER(3) NOT NULL,
	balance NUMBER(15,2) DEFAULT 0 NOT NULL,
	opening_date DATE DEFAULT SYSDATE NOT NULL,
	CONSTRAINT fk_acc_cust FOREIGN KEY (customer_id) REFERENCES customers(id),
	CONSTRAINT fk_acc_status FOREIGN KEY (status_id) REFERENCES account_statuses(id),
	CONSTRAINT fk_acc_type FOREIGN KEY (type_id) REFERENCES account_types(id)
);

	
CREATE TABLE lines_of_credit (
	account_id NUMBER(19) PRIMARY KEY,
	credit_limit NUMBER(8,2) NOT NULL, --we are not going to allow more than 999 999.99
	annual_interest_rate NUMBER(4,2) NOT NULL, --we are going to allow maximum 22.00%
	number_of_installments NUMBER(2) NOT NULL,
	CONSTRAINT fk_line_of_credit_base FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
);


CREATE TABLE credit_accounts (
	account_id NUMBER(19) PRIMARY KEY,
	credit_limit NUMBER(8,2) NOT NULL,
	annual_interest_rate NUMBER(4,2) NOT NULL,
	min_monthly_payment NUMBER(6,2) NOT NULL,
	payment_due_date DATE NOT NULL,
	last_interest_date DATE NOT NULL,
	CONSTRAINT fk_credit_acc_base FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
);

CREATE TABLE currency_accounts (	
	account_id NUMBER(19) PRIMARY KEY,
	account_currency VARCHAR2(30) NOT NULL,
	exchange_rate NUMBER(6,2) NOT NULL,
	balance_foreign_currency number(10,2) NOT NULL,
	CONSTRAINT fk_currency_acc_base FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
);

CREATE TABLE saving_accounts (
	account_id NUMBER(19) PRIMARY KEY,
	annual_interest_rate NUMBER(4,2) NOT NULL,
	last_interest_date DATE NOT NULL,
	CONSTRAINT fk_saving_acc_base FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
);

CREATE TABLE checking_accounts (
	account_id NUMBER(19) PRIMARY KEY,
	free_transactions_counter NUMBER(1) DEFAULT 3 NOT NULL,
	transaction_fee NUMBER(5,2) NOT NULL,
	last_reset_date DATE NOT NULL,
	CONSTRAINT fk_checking_acc_base FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
);

CREATE TABLE alert_types (
	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(30) NOT NULL,
	description VARCHAR(250) DEFAULT NULL
);

CREATE TABLE alerts (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	message CLOB NOT NULL, --mensaje especifico relacionado a la transaccion o al request account
	type_id NUMBER(3) NOT NULL,
	bank_manager_customer_id NUMBER(19), 
	CONSTRAINT fk_alerts_bank_manager_customer FOREIGN KEY (bank_manager_customer_id) REFERENCES bank_managers_customers(id) --change
);

CREATE TABLE transaction_types (
	id NUMBER(3) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR2(30) NOT NULL,
	description VARCHAR(250) NOT NULL	
);

CREATE TABLE transactions (
	id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	type_id NUMBER(3) NOT NULL,
	amount NUMBER(8,2) NOT NULL,
	transaction_date DATE DEFAULT SYSDATE NOT NULL,
	source_account_id NUMBER(19), -- Nullable for initial deposits/external cash
	target_account_id NUMBER(19), -- Nullable for cash withdrawals
	fee NUMBER(7,2) NOT NULL,
	alert_id NUMBER(19) NOT NULL, --succesfull, unsuccessfull, etc
	CONSTRAINT fk_transaction_type FOREIGN KEY (type_id) REFERENCES transaction_types(id),
	CONSTRAINT fk_trans_source FOREIGN KEY (source_account_id) REFERENCES accounts(id),
    	CONSTRAINT fk_trans_target FOREIGN KEY (target_account_id) REFERENCES accounts(id),
	CONSTRAINT fk_trans_alert FOREIGN KEY (alert_id) REFERENCES alerts(id)
);

